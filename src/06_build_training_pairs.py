#!/usr/bin/env python3

"""
STEP 6 — BUILD MEMORY-SAFE TRAINING PAIRS

Uses train_ground_truth.tsv directly.

Creates:
    output/training_pairs.tsv

Strategy:
    - stream the ground truth
    - keep positive S1 -> S2/S3 pairs
    - sample a controlled number of negatives
    - never load the complete ground truth into RAM

The negative examples are generated by pairing an S1 with
another record from the same source/country using deterministic
sampling. They are NOT assumed to be true matches.

No external data is used.
"""

from pathlib import Path
import csv
import random
import sqlite3
import time
import sys


BASE_DIR = Path(__file__).resolve().parent.parent

GROUND_TRUTH = (
    BASE_DIR
    / "dataset"
    / "train"
    / "train_ground_truth.tsv"
)

DB_PATH = (
    BASE_DIR
    / "output"
    / "entity_indexes.sqlite"
)

OUTPUT_DIR = BASE_DIR / "output"

OUTPUT_PATH = (
    OUTPUT_DIR
    / "training_pairs.tsv"
)

# ------------------------------------------------------------------
# CONFIGURATION
# ------------------------------------------------------------------

# Maximum positive examples.
# The complete GT contains ~7.64M positives.
# This keeps training manageable.
MAX_POSITIVES = 1_500_000

# Number of negatives.
MAX_NEGATIVES = 1_500_000

# Read GT in chunks.
GT_PROGRESS = 100_000

# Deterministic randomness.
RANDOM_SEED = 42

# Negative generation:
# select a different entity from the same country/source.
NEGATIVE_ATTEMPTS = 8


def check_files():

    if not GROUND_TRUTH.exists():
        print("ERROR: ground truth not found:")
        print(GROUND_TRUTH)
        sys.exit(1)

    if not DB_PATH.exists():
        print("ERROR: SQLite database not found:")
        print(DB_PATH)
        sys.exit(1)


def open_db():

    conn = sqlite3.connect(str(DB_PATH))

    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA synchronous=NORMAL")
    conn.execute("PRAGMA temp_store=FILE")
    conn.execute("PRAGMA cache_size=-12000")

    return conn


